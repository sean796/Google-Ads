import type { OverviewTabContentProps } from "@/components/overview/overview-tab/overview-tab-content-types";
import { useOverviewTabControllerCore } from "@/hooks/overview/use-overview-tab-controller-core";
import { useOverviewTabControllerBlog } from "@/hooks/overview/use-overview-tab-controller-blog";

export function useOverviewTabController(props: OverviewTabContentProps) {
  const {
    base,
    sitemapLoad,
    scrapeWp,
    faq,
    aiCsv,
    aiTitleHarness,
    aiMetaHarness,
    keywordsHarness,
    aiUrlHarness,
    kwDates,
    dfs,
    pipelines,
    bulkSeoWp,
    aiseoUploadAfterRowWrite,
  } = useOverviewTabControllerCore(props);

  const {
    blogHeaders,
    contentCleanup,
    blogLinks,
    blogWikipediaLink,
    blogOverview,
    blogAnswer,
    blogScenario,
    blogInContentImage,
    handleAiTitleRow,
    handleAiTitleAll,
    handleAiMetaRow,
    handleAiMetaAll,
    handleAiUrlRow,
    handleAiUrlAll,
    handleKeywordsAll,
    handleAiKeywordRow,
    handleAiFaqQuestion,
    handleAiFaqAnswer,
    handleAiFaqRowAll,
    handleAiFaqAll,
    handleAiAllMetaRow,
    handleAiAllMetaAll,
    handleAiAnswerRow,
    handleAiAnswerAll,
    handleAiOverviewRow,
    handleAiOverviewAll,
    handleAiScenarioRow,
    handleAiScenarioAll,
    handleAiHeadersRow,
    handleAiHeadersAll,
    handleAiLinksRow,
    handleAiLinksAll,
    handleAiWikipediaLinkRow,
    handleAiWikipediaLinkAll,
    handleAiInContentImageRow,
    handleAiInContentImageAll,
    handleAiFeaturedImageAll,
    handleFindLocalImageAll,
    handleGenerateLocalImageAll,
    handleContentCleanupRow,
    handleContentCleanupAll,
  } = useOverviewTabControllerBlog({
    props,
    base,
    aiseoUploadAfterRowWrite,
    pipelines,
    faq,
    aiTitleHarness,
    aiMetaHarness,
    aiUrlHarness,
    keywordsHarness,
  });

  return {
    site: props.site,
    ...base,
    overviewSitemapLoadBusy: sitemapLoad.overviewSitemapLoadBusy,
    handleLoadSitemap: sitemapLoad.handleLoadSitemap,
    handleRefreshSitemap: () =>
      sitemapLoad.handleLoadSitemap({ force: true, silent: false, applyToUi: true }),
    ...scrapeWp,
    ...aiCsv,
    ...kwDates,
    handleKeywordsAll,
    handleAiKeywordRow,
    ...faq,
    ...dfs,
    ...pipelines,
    ...bulkSeoWp,
    ...blogHeaders,
    ...contentCleanup,
    ...blogLinks,
    ...blogWikipediaLink,
    ...blogOverview,
    ...blogAnswer,
    ...blogScenario,
    ...blogInContentImage,
    handleAiTitleRow,
    handleAiTitleAll,
    handleAiMetaRow,
    handleAiMetaAll,
    handleAiUrlRow,
    handleAiUrlAll,
    handleAiFaqQuestion,
    handleAiFaqAnswer,
    handleAiFaqRowAll,
    handleAiFaqAll,
    handleAiAllMetaRow,
    handleAiAllMetaAll,
    handleAiAnswerRow,
    handleAiAnswerAll,
    handleAiOverviewRow,
    handleAiOverviewAll,
    handleAiScenarioRow,
    handleAiScenarioAll,
    handleAiHeadersRow,
    handleAiHeadersAll,
    handleAiLinksRow,
    handleAiLinksAll,
    handleAiWikipediaLinkRow,
    handleAiWikipediaLinkAll,
    handleAiInContentImageRow,
    handleAiInContentImageAll,
    handleAiFeaturedImageAll,
    handleFindLocalImageAll,
    handleGenerateLocalImageAll,
    handleContentCleanupRow,
    handleContentCleanupAll,
  };
}

export type OverviewTabController = ReturnType<typeof useOverviewTabController>;
