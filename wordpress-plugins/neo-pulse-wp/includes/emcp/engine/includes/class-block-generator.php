	/**
	 * Block supports a spec may switch on, keyed by the spec name, mapped to the
	 * block.json key WordPress reads. Border is still `__experimentalBorder` in
	 * core, so specs use the stable-looking `border` and the generator
	 * translates it.
	 *
	 * @since 3.20.0
	 *
	 * @return array<string, string>
	 */
	public static function supported_supports(): array {
		return array(
			'align'      => 'align',
			'color'      => 'color',
			'spacing'    => 'spacing',
			'typography' => 'typography',
			'border'     => '__experimentalBorder',
			'shadow'     => 'shadow',
			'dimensions' => 'dimensions',
			'background' => 'background',
		);
	}

	/**
	 * Attribute names WordPress itself adds or reads for block supports and
	 * editor features. A spec attribute with one of these names collides with
	 * the core attribute (e.g. a left/center/right `align` setting would be
	 * overwritten by the wide/full block alignment), so they are refused.
	 * Compared after sanitize_key(), so camelCase names are lowercased here.
	 *
	 * @since 3.20.0
	 *
	 * @return string[]
	 */
	private static function reserved_attribute_names(): array {
		return array( 'align', 'classname', 'style', 'backgroundcolor', 'textcolor', 'gradient', 'fontsize', 'fontfamily', 'bordercolor', 'shadow', 'anchor', 'lock', 'metadata', 'layout' );
	}

	/**
	 * Refuses a spec an agent is writing now when an attribute uses a name
	 * WordPress reserves. Called by the create, update and validate tools only,
	 * not by validate_spec(): a block already stored, or arriving through an
	 * import, Cloud pull or Marketplace install, keeps compiling as before.
	 *
	 * @since 3.20.0
	 *
	 * @param array $spec The block spec.
	 * @return WP_Error|null Null when every name is allowed.
	 */
	public static function reserved_name_error( array $spec ): ?WP_Error {
		foreach ( (array) ( $spec['attributes'] ?? array() ) as $attr ) {
			$name = is_array( $attr ) ? sanitize_key( (string) ( $attr['name'] ?? '' ) ) : '';
			if ( '' !== $name && in_array( $name, self::reserved_attribute_names(), true ) ) {
				return new WP_Error(
					'reserved_attribute_name',
					/* translators: 1: the reserved attribute name, 2: a suggested replacement. */
					sprintf( __( 'The attribute name %1$s is reserved by WordPress for block supports. Choose another name, e.g. %2$s.', 'emcp-tools' ), (string) $attr['name'], 'content_' . $name )
				);
			}
		}
		return null;
	}

	/**
	 * Validates a repeater attribute's row fields and options.
	 *
	 * @since 3.20.0
	 *
	 * @param array $attr The repeater attribute def.
	 * @return true|WP_Error
	 */
	private static function validate_repeater( array $attr ) {
		$label = sanitize_key( $attr['name'] );
		if ( empty( $attr['fields'] ) || ! is_array( $attr['fields'] ) ) {
			/* translators: %s: the repeater attribute name. */
			return new WP_Error( 'invalid_spec', sprintf( __( 'The repeater %s needs a fields array.', 'emcp-tools' ), $label ) );
		}

		$types = self::attribute_types();
		$seen  = array();
		foreach ( $attr['fields'] as $field ) {
			if ( ! is_array( $field ) || empty( $field['name'] ) || empty( $field['type'] ) ) {
				/* translators: %s: the repeater attribute name. */
				return new WP_Error( 'invalid_spec', sprintf( __( 'Each field of the repeater %s needs a name and a type.', 'emcp-tools' ), $label ) );
			}
			$name = sanitize_key( $field['name'] );
			if ( '' === $name || isset( $seen[ $name ] ) ) {
				/* translators: %s: the repeater attribute name. */
				return new WP_Error( 'invalid_spec', sprintf( __( 'Field names in the repeater %s must be unique lowercase identifiers.', 'emcp-tools' ), $label ) );
			}
			$seen[ $name ] = true;
			if ( 'repeater' === $field['type'] || ! isset( $types[ $field['type'] ] ) ) {
				return new WP_Error(
					'invalid_spec',
					/* translators: 1: the field type, 2: the repeater attribute name. */
					sprintf( __( 'Unsupported field type %1$s in the repeater %2$s (nested repeaters are not supported).', 'emcp-tools' ), (string) $field['type'], $label )
				);
			}
			if ( 'select' === $field['type'] && empty( $field['options'] ) ) {
				return new WP_Error( 'invalid_spec', __( 'A select field needs an options array.', 'emcp-tools' ) );
			}
			if ( isset( $field['media_types'] ) && ( 'media' !== $field['type'] || ! is_array( $field['media_types'] ) || array() === $field['media_types']
				|| array_diff( $field['media_types'], self::allowed_media_types() ) ) ) {
				return new WP_Error( 'invalid_spec', __( 'media_types is only for media fields and must use image, video, audio or application.', 'emcp-tools' ) );
			}
		}

		foreach ( $attr['fields'] as $field ) {
			if ( 'media' === $field['type'] ) {
				foreach ( array_keys( self::media_companions() ) as $suffix ) {
					if ( isset( $seen[ sanitize_key( $field['name'] ) . $suffix ] ) ) {
						return new WP_Error( 'invalid_spec', __( 'A repeater field name collides with a media field\'s _alt or _id companion. Rename it.', 'emcp-tools' ) );
					}
				}
			}
		}

		if ( isset( $attr['title_field'] ) && ! isset( $seen[ sanitize_key( (string) $attr['title_field'] ) ] ) ) {
			return new WP_Error( 'invalid_spec', __( 'title_field must name one of the repeater fields.', 'emcp-tools' ) );
		}
		foreach ( array( 'min_rows', 'max_rows' ) as $key ) {
			if ( isset( $attr[ $key ] ) && ( ! is_numeric( $attr[ $key ] ) || (int) $attr[ $key ] < 0 ) ) {
				/* translators: %s: min_rows or max_rows. */
				return new WP_Error( 'invalid_spec', sprintf( __( '%s must be a whole number of 0 or more.', 'emcp-tools' ), $key ) );
			}
		}
		if ( ! empty( $attr['max_rows'] ) && isset( $attr['min_rows'] ) && (int) $attr['min_rows'] > (int) $attr['max_rows'] ) {
			return new WP_Error( 'invalid_spec', __( 'min_rows cannot be larger than max_rows.', 'emcp-tools' ) );
		}

		return true;
	}

	/**
	 * Media types a `media` attribute may allow in its picker.
	 *
	 * @since 3.20.0
	 *
	 * @return string[]
	 */
	private static function allowed_media_types(): array {
		return array( 'image', 'video', 'audio', 'application' );
	}

	/**
	 * Read-only companion fields exposed for a `media` attribute, so a template
	 * can print the alt text and attachment ID without a dotted-path syntax.
	 *
	 * @since 3.20.0
	 *
	 * @return array<string, string> suffix => key inside the stored media object.
	 */
	private static function media_companions(): array {
		return array(
			'_alt' => 'alt',
			'_id'  => 'id',
		);
	}

	/**
	 * Maps an attribute `type` (the block-spec vocabulary) to the template
	 * compiler's escape-type vocabulary (the widget-spec vocabulary), so
	 * render.php gets the correct per-type escaping from the shared compiler.
	 *
	 * Two mappings are deliberately NOT the naive 1:1 name match, because the
	 * compiler's vocabulary was designed around Elementor widget control
	 * storage shapes, which block attributes don't share:
	 *
	 * - `boolean` -> `text` (NOT `switcher`). The compiler's `switcher` type
	 *   compiles `{{#if}}` to `'yes' === $expr`, because Elementor's SWITCHER
	 *   control stores the string 'yes'/''. A Gutenberg boolean attribute is a
	 *   real PHP true/false at render time, so `'yes' === true` would always
	 *   be false and the conditional would never render. `text`'s `{{#if}}`
	 *   branch is `! empty( $expr )`, which correctly treats true as truthy
	 *   and false as empty.
	 * - `url` -> `raw_url` (NOT `url`). The compiler's `url` type reads a
	 *   `['url']` subkey (`esc_url( $expr['url'] ?? '' )`), matching
	 *   Elementor's URL control which stores `{url, is_external, nofollow}`.
	 *   edit.js stores a `url`-type attribute as a plain string (TextControl),
	 *   so reading a `['url']` subkey off a string always yields ''. `raw_url`
	 *   escapes the value directly (`esc_url( $expr ?? '' )`), which matches
	 *   what edit.js actually stores. `media` IS left mapped to `media`
	 *   because edit.js's MediaUpload control stores `{id, url}`, so the
	 *   `['url']` subkey read is correct for that one.
	 *
	 * @since 3.7.0
	 *
	 * @return array<string, string>
	 */
	private static function compiler_escape_types(): array {
		return array(
			'string'   => 'text',
			'richtext' => 'wysiwyg',
			'number'   => 'number',
			'boolean'  => 'text',
			'select'   => 'text',
			'color'    => 'text',
			'media'    => 'media',
			'url'      => 'raw_url',
			'repeater' => 'repeater',
		);
	}

	/**
	 * Validates a block spec.
	 *
	 * @since 3.7.0
	 *
	 * @param mixed $spec The raw spec.
	 * @return true|WP_Error
	 */
	public static function validate_spec( $spec ) {
		if ( ! is_array( $spec ) || empty( $spec['meta']['title'] ) ) {
			return new WP_Error( 'invalid_spec', __( 'meta.title is required.', 'emcp-tools' ) );
		}
		if ( empty( $spec['attributes'] ) || ! is_array( $spec['attributes'] ) ) {
			return new WP_Error( 'invalid_spec', __( 'At least one attribute is required.', 'emcp-tools' ) );
		}
		if ( empty( $spec['html_template'] ) || ! is_string( $spec['html_template'] ) ) {
			return new WP_Error( 'invalid_spec', __( 'html_template is required.', 'emcp-tools' ) );
		}

		$types = self::attribute_types();
		$seen  = array();

		foreach ( $spec['attributes'] as $attr ) {
			if ( ! is_array( $attr ) || empty( $attr['name'] ) || empty( $attr['type'] ) ) {
				return new WP_Error( 'invalid_spec', __( 'Each attribute needs a name and a type.', 'emcp-tools' ) );
			}

			$name = sanitize_key( $attr['name'] );
			if ( '' === $name || isset( $seen[ $name ] ) ) {
				return new WP_Error( 'invalid_spec', __( 'Attribute names must be unique lowercase identifiers.', 'emcp-tools' ) );
			}
			$seen[ $name ] = true;

			if ( ! isset( $types[ $attr['type'] ] ) ) {
				return new WP_Error(
					'invalid_spec',
					/* translators: %s: the unsupported attribute type. */
					sprintf( __( 'Unsupported attribute type: %s.', 'emcp-tools' ), $attr['type'] )
				);
			}

			if ( 'select' === $attr['type'] && empty( $attr['options'] ) ) {
				return new WP_Error( 'invalid_spec', __( 'A select attribute needs an options array.', 'emcp-tools' ) );
			}

			if ( isset( $attr['group'] ) && ! is_string( $attr['group'] ) ) {
				return new WP_Error( 'invalid_spec', __( 'An attribute group must be a string (the sidebar panel title).', 'emcp-tools' ) );
			}

			if ( isset( $attr['media_types'] ) ) {
				if ( 'media' !== $attr['type'] || ! is_array( $attr['media_types'] ) || array() === $attr['media_types']
					|| array_diff( $attr['media_types'], self::allowed_media_types() ) ) {
					return new WP_Error(
						'invalid_spec',
						/* translators: %s: comma-separated list of allowed media types. */
						sprintf( __( 'media_types is only for media attributes and must list one or more of: %s.', 'emcp-tools' ), implode( ', ', self::allowed_media_types() ) )
					);
				}
			}

			if ( 'repeater' === $attr['type'] ) {
				$check = self::validate_repeater( $attr );
				if ( is_wp_error( $check ) ) {
					return $check;
				}
			}
		}

		// A media attribute exposes {{name_alt}} / {{name_id}}; a separately
		// declared attribute with one of those names would be silently shadowed.
		foreach ( $spec['attributes'] as $attr ) {
			if ( 'media' !== $attr['type'] ) {
				continue;
			}
			foreach ( array_keys( self::media_companions() ) as $suffix ) {
				$companion = sanitize_key( $attr['name'] ) . $suffix;
				if ( isset( $seen[ $companion ] ) ) {
					return new WP_Error(
						'invalid_spec',
						/* translators: %s: the reserved attribute name. */
						sprintf( __( 'The attribute name %s is reserved for the media attribute it belongs to. Rename it.', 'emcp-tools' ), $companion )
					);
				}
			}
		}

		// Unknown `supports` keys stay silently ignored (build_block_json() only
		// copies the allowlisted ones), as before, so stored specs keep compiling.

		return true;
	}

	/**
	 * Generates the four block assets from a spec.
	 *
	 * @since 3.7.0
	 *
	 * @param array $spec The block spec (meta, attributes, html_template, styles).
	 * @param int   $id   The numeric id used to build the block name (emcp/custom-{id}).
	 * @param array $opts Optional overrides: style_handle, editor_handle.
	 * @return array{block.json: string, render.php: string, edit.js: string, style.css: string}|WP_Error
	 */
	public static function generate( array $spec, int $id, array $opts = array() ) {
		$valid = self::validate_spec( $spec );
		if ( is_wp_error( $valid ) ) {
			return $valid;
		}

		$block_json = self::build_block_json( $spec, $id, $opts );
		$render_php = self::build_render_php( $spec );
		$edit_js    = self::build_edit_js( $spec, $id );
		$style_css  = ( isset( $spec['styles'] ) && is_string( $spec['styles'] ) )
			? preg_replace( '/<\?(?:php|=)?/i', '', trim( $spec['styles'] ) )
			: '';

		try {
			$tokens = token_get_all( $render_php, TOKEN_PARSE );
			unset( $tokens );
		} catch ( \ParseError $e ) {
			return new WP_Error(
				'generate_parse_error',
				__( 'The generated block render code failed a syntax check.', 'emcp-tools' ),
				array( 'detail' => $e->getMessage() )
			);
		}

		return array(
			'block.json' => $block_json,
			'render.php' => $render_php,
			'edit.js'    => $edit_js,
			'style.css'  => (string) $style_css,
		);
	}

	/**
	 * Coerces a raw default value to match a JSON Schema attribute type.
	 *
	 * @since 3.7.0
	 *
	 * @param mixed  $default   The raw default from the spec.
	 * @param string $json_type The attribute's JSON Schema type.
	 * @return mixed
	 */
	private static function coerce_default( $default, string $json_type ) {
		switch ( $json_type ) {
			case 'boolean':
				return (bool) $default;
			case 'number':
				return is_numeric( $default ) ? $default + 0 : 0;
			case 'array':
				return is_array( $default ) ? array_values( array_filter( $default, 'is_array' ) ) : array();
			case 'object':
				// An empty PHP array would encode as [] in block.json; an object attribute needs {}.
				return ( is_array( $default ) && array() !== $default ) ? $default : new stdClass();
			default:
				return (string) ( $default ?? '' );
		}
	}

	/**
	 * Builds the block.json contents.
	 *
	 * @since 3.7.0
	 *
	 * @param array $spec The validated spec.
	 * @param int   $id   The block id.
	 * @param array $opts Optional overrides: style_handle, editor_handle.
	 * @return string JSON.
	 */
	private static function build_block_json( array $spec, int $id, array $opts ): string {
		$types = self::attribute_types();
		$meta  = is_array( $spec['meta'] ?? null ) ? $spec['meta'] : array();

		$attributes = array();
		foreach ( $spec['attributes'] as $attr ) {
			$name      = sanitize_key( $attr['name'] );
			$json_type = $types[ $attr['type'] ]['json_type'];
			$attributes[ $name ] = array(
				'type'    => $json_type,
				'default' => self::coerce_default( $attr['default'] ?? null, $json_type ),
			);
		}

		$supports_in = is_array( $spec['supports'] ?? null ) ? $spec['supports'] : array();
		$supports    = array( 'html' => false );
		foreach ( self::supported_supports() as $key => $json_key ) {
			if ( array_key_exists( $key, $supports_in ) && ( is_bool( $supports_in[ $key ] ) || is_array( $supports_in[ $key ] ) ) ) {
				$supports[ $json_key ] = $supports_in[ $key ];
			}
		}

		$data = array(
			'$schema'     => 'https://schemas.wp.org/trunk/block.json',
			'apiVersion'  => 3,
			'name'        => 'emcp/custom-' . $id,
			'title'       => (string) ( $meta['title'] ?? ( 'Custom Block ' . $id ) ),
			// Pinned — never spec-configurable; see the CATEGORY constant doc.
			'category'    => self::CATEGORY,
			'icon'        => sanitize_key( $meta['icon'] ?? 'block-default' ),
			'description' => (string) ( $meta['description'] ?? '' ),
			'keywords'    => array_map( 'sanitize_text_field', (array) ( $meta['keywords'] ?? array() ) ),
			// validate_spec() guarantees at least one attribute, so this is
			// always a non-empty assoc array and encodes as a JSON object.
			'attributes'  => $attributes,
			'supports'    => $supports,
			// `render` is resolved by WordPress to a filesystem PATH (realpath of the
			// metadata dir + this ref), so it works for a sandbox under uploads.
			// editorScript/style are deliberately OMITTED: WordPress would resolve their
			// `file:` refs to a URL assuming a plugin/theme location, which is broken for
			// uploads-based blocks (it prefixes the plugins dir onto the absolute path).
			// EMCP_Tools_Block_Loader registers the editor script + style itself (correct
			// uploads URL + real wp-* deps) and passes the handles to register_block_type().
			'render'      => 'file:./render.php',
		);

		return (string) wp_json_encode( $data, JSON_PRETTY_PRINT );
	}

	/**
	 * Builds the render.php contents.
	 *
	 * @since 3.7.0
	 *
	 * @param array $spec The validated spec.
	 * @return string PHP.
	 */
	private static function build_render_php( array $spec ): string {
		$types        = self::attribute_types();
		$escape_types = self::compiler_escape_types();

		$field_map  = array();
		$companions = '';
		foreach ( $spec['attributes'] as $attr ) {
			$name                = sanitize_key( $attr['name'] );
			$field_map[ $name ] = array(
				'type' => $escape_types[ $attr['type'] ] ?? 'text',
			);
			if ( 'media' === $attr['type'] ) {
				// Flatten {id, url, alt} into {{name_alt}} / {{name_id}} so templates
				// can print them with the compiler's ordinary per-type escaping.
				foreach ( self::media_companions() as $suffix => $key ) {
					$field_map[ $name . $suffix ] = array( 'type' => 'id' === $key ? 'number' : 'text' );
					$companions                  .= "\$attributes['{$name}{$suffix}'] = is_array( \$attributes['{$name}'] ?? null ) ? ( \$attributes['{$name}']['{$key}'] ?? '' ) : '';\n";
				}
			}
			if ( 'repeater' === $attr['type'] ) {
				// Typed row fields, so {{#each}} escapes each field by its own type,
				// plus the same alt/id companions for media fields inside a row.
				$rfields = array();
				$flatten = array();
				foreach ( (array) $attr['fields'] as $field ) {
					$fname             = sanitize_key( $field['name'] );
					$rfields[ $fname ] = array( 'type' => $escape_types[ $field['type'] ] ?? 'text' );
					// The editor preview sends rows in a query string, and core only
					// restores the types of top-level attributes: "false" must not be true.
					if ( 'boolean' === $field['type'] ) {
						$flatten[] = "\$emcp_row['{$fname}'] = filter_var( \$emcp_row['{$fname}'] ?? false, FILTER_VALIDATE_BOOLEAN );";
					} elseif ( 'number' === $field['type'] ) {
						$flatten[] = "\$emcp_row['{$fname}'] = is_numeric( \$emcp_row['{$fname}'] ?? null ) ? \$emcp_row['{$fname}'] + 0 : '';";
					}
					if ( 'media' === $field['type'] ) {
						foreach ( self::media_companions() as $suffix => $key ) {
							$rfields[ $fname . $suffix ] = array( 'type' => 'id' === $key ? 'number' : 'text' );
							$flatten[]                   = "\$emcp_row['{$fname}{$suffix}'] = is_array( \$emcp_row['{$fname}'] ?? null ) ? ( \$emcp_row['{$fname}']['{$key}'] ?? '' ) : '';";
						}
					}
				}
				$field_map[ $name ]['fields'] = $rfields;
				// Rows always become a list of arrays, whatever was stored.
				$companions .= "\$attributes['{$name}'] = is_array( \$attributes['{$name}'] ?? null ) ? array_values( array_filter( \$attributes['{$name}'], 'is_array' ) ) : array();\n";
				if ( $flatten ) {
					$companions .= "foreach ( \$attributes['{$name}'] as &\$emcp_row ) { " . implode( ' ', $flatten ) . " } unset( \$emcp_row );\n";
				}
			}
		}
		unset( $types );

		$body = EMCP_Tools_Sandbox_Template_Compiler::compile( (string) $spec['html_template'], $field_map, '$attributes' );

		// The file is consumed by WordPress's block.json `render` mechanism, which
		// wraps it in its own `ob_start(); require $file; return ob_get_clean();`
		// closure and IGNORES the file's return value. So render.php must ECHO its
		// markup directly (no self-buffering / return, or the caller's buffer stays
		// empty and the block renders nothing). $attributes/$content/$block are in
		// scope courtesy of that closure.
		$php  = "<?php\n";
		$php .= "/**\n * Generated by Neo EMCP. DO NOT EDIT.\n";
		$php .= " * Source of truth: the emcp_block post's _emcp_spec meta. Regenerate via the plugin.\n */\n";
		$php .= "if ( ! defined( 'ABSPATH' ) ) { exit; }\n";
		$php .= "\$attributes = isset( \$attributes ) && is_array( \$attributes ) ? \$attributes : array();\n";
		$php .= $companions;
		$php .= "ob_start();\n";
		$php .= $body;
		$php .= "\$emcp_html = (string) ob_get_clean();\n";
		$php .= self::wrapper_merge_php();

		return $php;
	}

	/**
	 * PHP appended to every render.php: merges WordPress's block wrapper
	 * attributes (block-supports classes and inline styles, the "Additional CSS
	 * class" field, alignment) into the template's first element, so supports
	 * chosen in the editor actually reach the front end without adding an extra
	 * wrapper element. Uses only core APIs, so it keeps working in a Sandbox
	 * plugin export with Neo EMCP deactivated.
	 *
	 * Skipped inside the editor's ServerSideRender preview (the block-renderer
	 * REST route with context=edit): there the editor's own useBlockProps()
	 * wrapper already carries the same classes and styles, and applying them
	 * twice would double padding, borders and backgrounds. Other REST requests
	 * with context=edit (a post's content.rendered) keep the styles.
	 *
	 * @since 3.20.0
	 *
	 * @return string PHP statements.
	 */
	private static function wrapper_merge_php(): string {
		return <<<'PHP'
$emcp_is_preview = function_exists( 'wp_is_serving_rest_request' ) && wp_is_serving_rest_request()
	&& false !== strpos( (string) ( $_SERVER['REQUEST_URI'] ?? '' ), 'block-renderer' ) // phpcs:ignore WordPress.Security.ValidatedSanitizedInput -- only searched for a route name.
	&& isset( $_REQUEST['context'] ) && 'edit' === sanitize_key( wp_unslash( $_REQUEST['context'] ) ); // phpcs:ignore WordPress.Security.NonceVerification.Recommended -- read-only render context flag.
$emcp_wrapper = ( ! $emcp_is_preview && function_exists( 'get_block_wrapper_attributes' ) ) ? get_block_wrapper_attributes() : '';
if ( '' !== $emcp_wrapper && class_exists( 'WP_HTML_Tag_Processor' ) ) {
	$emcp_root = new WP_HTML_Tag_Processor( $emcp_html );
	$emcp_from = new WP_HTML_Tag_Processor( '<div ' . $emcp_wrapper . '>' );
	if ( $emcp_root->next_tag() && $emcp_from->next_tag() ) {
		foreach ( (array) $emcp_from->get_attribute_names_with_prefix( '' ) as $emcp_attr ) {
			$emcp_value = (string) $emcp_from->get_attribute( $emcp_attr );
			if ( 'class' === $emcp_attr ) {
				foreach ( preg_split( '/\s+/', $emcp_value, -1, PREG_SPLIT_NO_EMPTY ) as $emcp_class ) {
					$emcp_root->add_class( $emcp_class );
				}
			} elseif ( 'style' === $emcp_attr ) {
				$emcp_old = trim( (string) $emcp_root->get_attribute( 'style' ), " ;\t\n" );
				$emcp_root->set_attribute( 'style', '' === $emcp_old ? $emcp_value : $emcp_old . ';' . $emcp_value );
			} elseif ( null === $emcp_root->get_attribute( $emcp_attr ) ) {
				$emcp_root->set_attribute( $emcp_attr, $emcp_value );
			}
		}
		$emcp_html = $emcp_root->get_updated_html();
	} else {
		$emcp_html = '<div ' . $emcp_wrapper . '>' . $emcp_html . '</div>';
	}
}
echo $emcp_html; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- every value was escaped by the compiled template; wrapper attributes come from core.

PHP;
	}

	/**
	 * Builds the edit.js contents — a plain no-build editor script, always
	 * generated by this class (never AI-authored raw JS).
	 *
	 * Attributes are grouped into sidebar panels by their optional `group`
	 * (default "Settings", in first-seen order, the first panel open). Color
	 * controls offer the active theme's palette, and media controls show a
	 * thumbnail with Replace / Remove.
	 *
	 * @since 3.7.0
	 * @since 3.20.0 Panels per group, help text, theme palette, media thumbnails.
	 *
	 * @param array $spec The validated spec.
	 * @param int   $id   The block id.
	 * @return string JS.
	 */
	private static function build_edit_js( array $spec, int $id ): string {
		$name = 'emcp/custom-' . $id;

		$groups = array();
		foreach ( $spec['attributes'] as $attr ) {
			$group = trim( (string) ( $attr['group'] ?? '' ) );
			$group = '' === $group ? 'Settings' : $group;
			if ( ! isset( $groups[ $group ] ) ) {
				$groups[ $group ] = array();
			}
			$groups[ $group ][] = self::build_control_js( $attr );
		}

		$panels = array();
		$first  = true;
		foreach ( $groups as $title => $controls ) {
			$title_json = wp_json_encode( (string) $title, JSON_UNESCAPED_SLASHES );
			$open       = $first ? 'true' : 'false';
			$panels[]   = "\t\t\t\tel( components.PanelBody, { key: {$title_json}, title: {$title_json}, initialOpen: {$open} },\n" . implode( ",\n", $controls ) . "\n\t\t\t\t)";
			$first      = false;
		}
		$panels_js = implode( ",\n", $panels );

		$name_json = wp_json_encode( $name, JSON_UNESCAPED_SLASHES );

		$js  = "/* Generated by Neo EMCP. DO NOT EDIT. */\n";
		$js .= "( function( blocks, blockEditor, components, element, ServerSideRender ) {\n";
		$js .= "\tvar el = element.createElement, Fragment = element.Fragment, useBlockProps = blockEditor.useBlockProps;\n";
		// The theme palette: useSettings (WP 6.5+) with a useSetting fallback.
		$js .= "\tfunction usePalette() {\n";
		$js .= "\t\tvar p = blockEditor.useSettings ? blockEditor.useSettings( 'color.palette' )[ 0 ] : ( blockEditor.useSetting ? blockEditor.useSetting( 'color.palette' ) : [] );\n";
		$js .= "\t\treturn Array.isArray( p ) ? p : [];\n";
		$js .= "\t}\n";
		$js .= "\tfunction isImage( v ) { return !! v && ( 'image' === v.type || /\\.(jpe?g|png|gif|webp|avif|svg)(\\?|$)/i.test( v.url || '' ) ); }\n";
		if ( in_array( 'repeater', array_column( $spec['attributes'], 'type' ), true ) ) {
			$js .= self::repeater_helpers_js();
		}
		$js .= "\tblocks.registerBlockType( {$name_json}, {\n";
		$js .= "\t\tedit: function( props ) {\n";
		$js .= "\t\t\tvar attributes = props.attributes, setAttributes = props.setAttributes;\n";
		$js .= "\t\t\tvar palette = usePalette();\n";
		$js .= "\t\t\treturn el( Fragment, {},\n";
		$js .= "\t\t\t\tel( blockEditor.InspectorControls, {},\n{$panels_js}\n\t\t\t\t),\n";
		$js .= "\t\t\t\tel( 'div', useBlockProps(), el( ServerSideRender, { block: {$name_json}, attributes: attributes } ) )\n";
		$js .= "\t\t\t);\n";
		$js .= "\t\t},\n";
		$js .= "\t\tsave: function() { return null; }\n";
		$js .= "\t} );\n";
		$js .= "} )( window.wp.blocks, window.wp.blockEditor, window.wp.components, window.wp.element, window.wp.serverSideRender );\n";

		return $js;
	}

	/**
	 * The data a repeater's editor control needs: its fields (with defaults
	 * coerced to their JSON types) and the row options. Pure data, encoded as
	 * JSON into edit.js; the behavior lives in repeater_helpers_js().
	 *
	 * @since 3.20.0
	 *
	 * @param array $attr The repeater attribute def.
	 * @return array
	 */
	private static function repeater_config( array $attr ): array {
		$types  = self::attribute_types();
		$fields = array();
		foreach ( (array) $attr['fields'] as $field ) {
			$json_type = $types[ $field['type'] ]['json_type'];
			$entry     = array(
				'name'    => sanitize_key( $field['name'] ),
				'type'    => (string) $field['type'],
				'label'   => (string) ( $field['label'] ?? $field['name'] ),
				'help'    => (string) ( $field['help'] ?? '' ),
				'default' => self::coerce_default( $field['default'] ?? null, $json_type ),
			);
			foreach ( array( 'min', 'max', 'step' ) as $num ) {
				if ( isset( $field[ $num ] ) && is_numeric( $field[ $num ] ) ) {
					$entry[ $num ] = (float) $field[ $num ];
				}
			}
			if ( 'select' === $field['type'] ) {
				$entry['options'] = array();
				foreach ( (array) $field['options'] as $opt ) {
					$entry['options'][] = array(
						'value' => (string) ( $opt['value'] ?? '' ),
						'label' => (string) ( $opt['label'] ?? ( $opt['value'] ?? '' ) ),
					);
				}
			}
			if ( 'media' === $field['type'] ) {
				$media_types          = isset( $field['media_types'] ) && is_array( $field['media_types'] )
					? array_values( array_intersect( $field['media_types'], self::allowed_media_types() ) )
					: array();
				$entry['media_types'] = $media_types ? $media_types : array( 'image' );
			}
			$fields[] = $entry;
		}

		$title = isset( $attr['title_field'] ) ? sanitize_key( (string) $attr['title_field'] ) : '';
		if ( '' === $title ) {
			foreach ( $fields as $field ) {
				if ( 'string' === $field['type'] ) {
					$title = $field['name'];
					break;
				}
			}
		}

		return array(
			'label'      => (string) ( $attr['label'] ?? $attr['name'] ),
			'help'       => (string) ( $attr['help'] ?? '' ),
			'fields'     => $fields,
			'titleField' => $title,
			'itemLabel'  => (string) ( $attr['item_label'] ?? 'Item' ),
			'addLabel'   => (string) ( $attr['add_label'] ?? 'Add item' ),
			'min'        => isset( $attr['min_rows'] ) ? (int) $attr['min_rows'] : 0,
			'max'        => isset( $attr['max_rows'] ) ? (int) $attr['max_rows'] : 0,
		);
	}

	/**
	 * The fixed repeater editor code: a per-field control renderer and the
	 * RepeaterControl component (rows that open one at a time, move up/down,
	 * remove, add, min/max rows). Plugin-owned and identical for every block;
	 * a spec only ever supplies the JSON config.
	 *
	 * @since 3.20.0
	 *
	 * @return string JS.
	 */
	private static function repeater_helpers_js(): string {
		return <<<'JS'
	function emptyValue( f ) {
		if ( f.default !== undefined && f.default !== null ) { return f.default; }
		return 'boolean' === f.type ? false : ( 'number' === f.type ? 0 : ( 'media' === f.type ? {} : '' ) );
	}
	function fieldControl( f, value, onChange, palette ) {
		var common = { label: f.label, help: f.help || undefined, __nextHasNoMarginBottom: true };
		function withProps( extra ) { return Object.assign( {}, common, extra ); }
		switch ( f.type ) {
			case 'boolean':
				return el( components.ToggleControl, withProps( { checked: !! value, onChange: onChange } ) );
			case 'number':
				return el( components.RangeControl, withProps( { __next40pxDefaultSize: true, min: null != f.min ? f.min : 0, max: null != f.max ? f.max : 100, step: f.step || 1, value: value, onChange: onChange } ) );
			case 'richtext':
				return el( components.TextareaControl, withProps( { value: value || '', onChange: onChange } ) );
			case 'select':
				return el( components.SelectControl, withProps( { __next40pxDefaultSize: true, value: value, options: f.options || [], onChange: onChange } ) );
			case 'color':
				return el( components.BaseControl, common, el( components.ColorPalette, { colors: palette, clearable: true, value: value, onChange: function( v ) { onChange( v || '' ); } } ) );
			case 'media':
				return el( components.BaseControl, common, el( blockEditor.MediaUploadCheck, {}, el( blockEditor.MediaUpload, {
					allowedTypes: f.media_types || [ 'image' ],
					value: ( value && value.id ) || undefined,
					onSelect: function( m ) { onChange( { id: m.id, url: m.url, alt: m.alt || '', type: m.type || '' } ); },
					render: function( obj ) {
						var v = value || {};
						return el( 'div', {},
							v.url ? ( isImage( v ) ? el( 'img', { src: v.url, alt: '', style: { display: 'block', width: '100%', maxHeight: '120px', objectFit: 'cover', borderRadius: '2px', marginBottom: '8px', background: '#f0f0f0' } } ) : el( 'p', { style: { wordBreak: 'break-all', margin: '0 0 8px' } }, v.url.split( '/' ).pop() ) ) : null,
							el( components.Button, { variant: 'secondary', onClick: obj.open }, v.url ? 'Replace' : 'Select' ),
							v.url ? el( components.Button, { variant: 'link', isDestructive: true, style: { marginLeft: '12px' }, onClick: function() { onChange( {} ); } }, 'Remove' ) : null
						);
					}
				} ) ) );
			case 'url':
				return el( components.TextControl, withProps( { __next40pxDefaultSize: true, type: 'url', value: value || '', onChange: onChange } ) );
			default:
				return el( components.TextControl, withProps( { __next40pxDefaultSize: true, value: value || '', onChange: onChange } ) );
		}
	}
	function RepeaterControl( props ) {
		var cfg = props.cfg, rows = Array.isArray( props.value ) ? props.value : [], set = props.onChange;
		var openState = element.useState( -1 ), open = openState[ 0 ], setOpen = openState[ 1 ];
		var canAdd = ! cfg.max || rows.length < cfg.max, canRemove = rows.length > ( cfg.min || 0 );
		function update( i, key, v ) {
			var next = rows.slice(), row = Object.assign( {}, next[ i ] );
			row[ key ] = v; next[ i ] = row; set( next );
		}
		function move( i, d ) {
			var j = i + d, next = rows.slice(), t;
			if ( j < 0 || j >= rows.length ) { return; }
			t = next[ i ]; next[ i ] = next[ j ]; next[ j ] = t; set( next );
			if ( open === i ) { setOpen( j ); }
		}
		function remove( i ) {
			var next = rows.slice(); next.splice( i, 1 ); set( next ); setOpen( -1 );
		}
		function add() {
			var row = {};
			cfg.fields.forEach( function( f ) { row[ f.name ] = emptyValue( f ); } );
			set( rows.concat( [ row ] ) ); setOpen( rows.length );
		}
		return el( components.BaseControl, { label: cfg.label, help: cfg.help || undefined, __nextHasNoMarginBottom: true },
			el( 'div', { style: { marginTop: '8px' } },
				rows.map( function( row, i ) {
					var isOpen = open === i;
					var title = ( cfg.titleField && row[ cfg.titleField ] ) ? String( row[ cfg.titleField ] ) : cfg.itemLabel + ' ' + ( i + 1 );
					return el( 'div', { key: i, style: { border: '1px solid #ddd', borderRadius: '2px', marginBottom: '8px', background: '#fff' } },
						el( 'div', { style: { display: 'flex', alignItems: 'center', gap: '2px', padding: '2px 2px 2px 4px', background: isOpen ? '#f6f7f7' : 'transparent' } },
							el( components.Button, { variant: 'tertiary', 'aria-expanded': isOpen, style: { flex: '1', minWidth: '0', justifyContent: 'flex-start', overflow: 'hidden', whiteSpace: 'nowrap', textOverflow: 'ellipsis' }, onClick: function() { setOpen( isOpen ? -1 : i ); } }, title ),
							el( components.Button, { icon: 'arrow-up-alt2', label: 'Move up', size: 'small', disabled: 0 === i, onClick: function() { move( i, -1 ); } } ),
							el( components.Button, { icon: 'arrow-down-alt2', label: 'Move down', size: 'small', disabled: i === rows.length - 1, onClick: function() { move( i, 1 ); } } ),
							el( components.Button, { icon: 'trash', label: 'Remove', size: 'small', isDestructive: true, disabled: ! canRemove, onClick: function() { remove( i ); } } )
						),
						isOpen ? el( 'div', { style: { padding: '12px', display: 'grid', gap: '16px', borderTop: '1px solid #ddd' } },
							cfg.fields.map( function( f ) {
								return el( 'div', { key: f.name }, fieldControl( f, row[ f.name ], function( v ) { update( i, f.name, v ); }, props.palette ) );
							} )
						) : null
					);
				} ),
				el( components.Button, { variant: 'secondary', icon: 'plus', disabled: ! canAdd, onClick: add }, cfg.addLabel ),
				cfg.max ? el( 'p', { style: { margin: '8px 0 0', fontSize: '12px', color: '#757575' } }, rows.length + ' of ' + cfg.max ) : null
			)
		);
	}

JS;
	}

	/**
	 * Builds one attribute's InspectorControls createElement() call.
	 *
	 * @since 3.7.0
	 * @since 3.20.0 Help text, theme palette for colors, media thumbnail.
	 *
	 * @param array $attr The raw attribute def from the spec.
	 * @return string A JS expression (no trailing comma).
	 */
	private static function build_control_js( array $attr ): string {
		$types   = self::attribute_types();
		$name    = sanitize_key( $attr['name'] );
		$type    = $attr['type'];
		$control = $types[ $type ]['control'] ?? 'text';
		$label   = wp_json_encode( (string) ( $attr['label'] ?? $attr['name'] ), JSON_UNESCAPED_SLASHES );
		$key     = wp_json_encode( $name, JSON_UNESCAPED_SLASHES );
		$help    = wp_json_encode( (string) ( $attr['help'] ?? '' ), JSON_UNESCAPED_SLASHES );
		$common  = "key: {$key}, label: {$label}, help: {$help} || undefined, __nextHasNoMarginBottom: true";
		$set     = "function( value ) { setAttributes( { {$name}: value } ); }";

		switch ( $control ) {
			case 'toggle':
				return "\t\t\t\t\tel( components.ToggleControl, { {$common}, checked: !! attributes.{$name}, onChange: {$set} } )";

			case 'range':
				$min  = wp_json_encode( isset( $attr['min'] ) ? (float) $attr['min'] : 0 );
				$max  = wp_json_encode( isset( $attr['max'] ) ? (float) $attr['max'] : 100 );
				$step = wp_json_encode( isset( $attr['step'] ) ? (float) $attr['step'] : 1 );
				return "\t\t\t\t\tel( components.RangeControl, { {$common}, __next40pxDefaultSize: true, min: {$min}, max: {$max}, step: {$step}, value: attributes.{$name}, onChange: {$set} } )";

			case 'richtext':
				return "\t\t\t\t\tel( components.TextareaControl, { {$common}, value: attributes.{$name}, onChange: {$set} } )";

			case 'select':
				$options = array();
				foreach ( (array) ( $attr['options'] ?? array() ) as $opt ) {
					$options[] = array(
						'value' => (string) ( $opt['value'] ?? '' ),
						'label' => (string) ( $opt['label'] ?? ( $opt['value'] ?? '' ) ),
					);
				}
				$options_json = wp_json_encode( $options, JSON_UNESCAPED_SLASHES );
				return "\t\t\t\t\tel( components.SelectControl, { {$common}, __next40pxDefaultSize: true, value: attributes.{$name}, options: {$options_json}, onChange: {$set} } )";

			case 'color':
				return "\t\t\t\t\tel( components.BaseControl, { {$common} }, el( components.ColorPalette, { colors: palette, clearable: true, value: attributes.{$name}, onChange: function( value ) { setAttributes( { {$name}: value || '' } ); } } ) )";

			case 'media':
				$media_types = isset( $attr['media_types'] ) && is_array( $attr['media_types'] )
					? array_values( array_intersect( $attr['media_types'], self::allowed_media_types() ) )
					: array( 'image' );
				$types_json  = wp_json_encode( $media_types ? $media_types : array( 'image' ) );
				return "\t\t\t\t\tel( components.BaseControl, { {$common} }, el( blockEditor.MediaUploadCheck, {}, el( blockEditor.MediaUpload, {"
					. " allowedTypes: {$types_json},"
					. " value: ( attributes.{$name} && attributes.{$name}.id ) || undefined,"
					. " onSelect: function( media ) { setAttributes( { {$name}: { id: media.id, url: media.url, alt: media.alt || '', type: media.type || '' } } ); },"
					. ' render: function( obj ) {'
					. " var v = attributes.{$name} || {};"
					. " return el( 'div', {},"
					. " v.url ? ( isImage( v ) ? el( 'img', { src: v.url, alt: '', style: { display: 'block', width: '100%', maxHeight: '160px', objectFit: 'cover', borderRadius: '2px', marginBottom: '8px', background: '#f0f0f0' } } ) : el( 'p', { style: { wordBreak: 'break-all', margin: '0 0 8px' } }, v.url.split( '/' ).pop() ) ) : null,"
					. " el( components.Button, { variant: 'secondary', onClick: obj.open }, v.url ? 'Replace' : 'Select' ),"
					. " v.url ? el( components.Button, { variant: 'link', isDestructive: true, style: { marginLeft: '12px' }, onClick: function() { setAttributes( { {$name}: {} } ); } }, 'Remove' ) : null"
					. ' ); } } ) ) )';

			case 'url':
				return "\t\t\t\t\tel( components.TextControl, { {$common}, __next40pxDefaultSize: true, type: 'url', value: attributes.{$name}, onChange: {$set} } )";

			case 'repeater':
				$cfg_json = wp_json_encode( self::repeater_config( $attr ), JSON_UNESCAPED_SLASHES );
				return "\t\t\t\t\tel( RepeaterControl, { key: {$key}, cfg: {$cfg_json}, value: attributes.{$name}, palette: palette, onChange: {$set} } )";

			case 'text':
			default:
				return "\t\t\t\t\tel( components.TextControl, { {$common}, __next40pxDefaultSize: true, value: attributes.{$name}, onChange: {$set} } )";
		}
	}
