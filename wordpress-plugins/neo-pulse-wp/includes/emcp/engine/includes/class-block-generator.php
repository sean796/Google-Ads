<?php
/**
 * Block Generator — compiles a structured spec into a dynamic Gutenberg
 * block's four assets: block.json, render.php, edit.js, style.css.
 *
 * This is the block-authoring counterpart to EMCP_Tools_Widget_Generator. The
 * AI never authors PHP or JS directly: it submits a JSON spec (meta +
 * attributes[] + an html_template using the shared `{{name}}` /
 * `{{#if}}`/`{{#each}}` DSL). The HTML->PHP compilation (and therefore all
 * output escaping) is delegated to EMCP_Tools_Sandbox_Template_Compiler, the
 * same audited component the Widget Builder uses. The editor script (edit.js)
 * is ALWAYS generated by this class from the attribute list — raw JS from a
 * spec is never accepted — so its safety is a property of this generator, not
 * of caller input. The result is structurally lint-checked with
 * `token_get_all( …, TOKEN_PARSE )` before it is ever written to disk.
 *
 * @package EMCP_Tools
 * @since   3.7.0
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/**
 * Compiles block specs into block.json + render.php + edit.js + style.css.
 *
 * @since 3.7.0
 */
class EMCP_Tools_Block_Generator {

	/**
	 * The single inserter category every generated block registers into.
	 * Deliberately not spec-configurable so custom blocks always land in one
	 * place regardless of what a caller passes as meta.category.
	 *
	 * @since 3.7.0
	 */
